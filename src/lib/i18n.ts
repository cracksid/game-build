const DICTS: Record<Lang, Dict> = { en, es, hi };

export type MessageArgs = Record<string, string | number>;

/**
 * Look up `key` in `lang`, falling back to English and finally to the key
 * itself -- a missing translation shows a readable string instead of a gap.
 */
export function translate(lang: Lang, key: string, args?: MessageArgs): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!args) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in args ? String(args[name]) : whole,
  );
}
